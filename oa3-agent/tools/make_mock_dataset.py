#!/usr/bin/env python3
"""Create a tiny synthetic dataset + config so that the whole OA-3 pipeline can be exercised with tools/mock_oa_slam.py.

  python tools/make_mock_dataset.py [--out mock_data] [--frames 400]
Writes  mock_data/<seq>/{rgb.txt, groundtruth.txt, camera.yaml, detections.json}  for three sequences and
        oa3_config_mock.yaml  at the package root (paths relative to the config).
"""
import argparse, json, math
from pathlib import Path
import numpy as np

SEQS = [("mock_dyn_a", "dynamic", 0.35), ("mock_dyn_b", "dynamic", 0.20), ("mock_control", "dynamic", 0.0)]  # (name, set, person rate)


def yaw_quat(yaw):
    return [0.0, 0.0, math.sin(yaw / 2), math.cos(yaw / 2)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="mock_data")
    ap.add_argument("--frames", type=int, default=400)
    a = ap.parse_args()
    here = Path(__file__).resolve().parent.parent
    out = (here / a.out).resolve()
    rng = np.random.default_rng(7)
    for name, sset, prate in SEQS:
        d = out / name
        d.mkdir(parents=True, exist_ok=True)
        n = a.frames
        t0 = 1305031000.0
        with open(d / "rgb.txt", "w") as fr, open(d / "groundtruth.txt", "w") as fg:
            fr.write("# color images\n# file: mock\n# timestamp filename\n")
            fg.write("# ground truth trajectory\n# timestamp tx ty tz qx qy qz qw\n")
            frames = []
            for i in range(n):
                t = t0 + i / 30.0
                ang = 2 * math.pi * i / n
                x, y, z = 1.5 * math.cos(ang), 1.0 * math.sin(ang), 0.1 * math.sin(3 * ang)
                q = yaw_quat(ang + math.pi / 2)
                fn = "rgb/%.6f.png" % t
                fr.write("%.6f %s\n" % (t, fn))
                fg.write("%.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f\n" % (t, x, y, z, q[0], q[1], q[2], q[3]))
                # ground truth also at intermediate times (like TUM's 100 Hz mocap)
                if i < n - 1:
                    for k in (1, 2):
                        tt = t + k / 90.0; ang2 = 2 * math.pi * (i + k / 3) / n
                        fg.write("%.4f %.4f %.4f %.4f %.4f %.4f %.4f %.4f\n" % (tt, 1.5 * math.cos(ang2), 1.0 * math.sin(ang2), 0.1 * math.sin(3 * ang2), *yaw_quat(ang2 + math.pi / 2)))
                dets = []
                for _ in range(int(rng.integers(0, 4))):
                    cat = int(rng.choice([56, 62, 63, 66, 73]))
                    dets.append({"category_id": cat, "detection_score": float(rng.uniform(0.3, 0.98)),
                                 "bbox": [float(v) for v in sorted(rng.uniform(0, 640, 2))] + [float(v) for v in sorted(rng.uniform(0, 480, 2))]})
                if rng.random() < prate:
                    dets.append({"category_id": 0, "detection_score": float(rng.uniform(0.5, 0.99)), "bbox": [200.0, 100.0, 380.0, 460.0]})
                frames.append({"file_name": fn, "detections": dets})
        with open(d / "detections.json", "w") as f:
            json.dump(frames, f)
        (d / "camera.yaml").write_text("%YAML:1.0\nCamera.fx: 525.0\nCamera.fy: 525.0\nCamera.cx: 319.5\nCamera.cy: 239.5\nCamera.fps: 30.0\n")
    cfg = """# Mock configuration generated by tools/make_mock_dataset.py (paths relative to this file)
project:
  oa_slam_root: mock_root
  executable: ./bin/oa-slam
  vocabulary: Vocabulary/ORBvoc.txt
  reloc_mode: points
  show_viewer: 0
  ignore_file: ""
  arg_template: "{exe} {vocab} {yaml} {frames_list} {det_json} {reloc_mode} {out_name} {show_viewer}"
  output_subdir: "{out_name}"
  output_files: []
  trajectory_for_eval: "camera_poses_{out_name}_tum.txt"
  map_objects_file: "map_objects_{out_name}.txt"
datasets:
"""
    for name, sset, prate in SEQS:
        cfg += """  %s:
    dataset: Mock
    set: %s
    seq_dir: %s/%s
    frames_list: %s/%s/rgb.txt
    gt: %s/%s/groundtruth.txt
    yaml: %s/%s/camera.yaml
    det_json: %s/%s/detections.json
""" % (name, sset, a.out, name, a.out, name, a.out, name, a.out, name, a.out, name)
    cfg += """ablation:
  runs_per_cell: 3
  include_default_cell: true
  default_cell_name: default
  default:
    OA_DET_SCORE: 0.5
    OA_IOU2D: 0.2
    OA_IOU3D: 0.3
    OA_TIME_DIFF: 30
    OA_NB_MATCH: 10
    OA_MIN_OBS: 10
    OA_MAP_OBS: 40
  cells:
    P1_loose:  { OA_IOU2D: 0.10, OA_IOU3D: 0.15 }
    P1_tight:  { OA_IOU2D: 0.40, OA_IOU3D: 0.50 }
    P2_low:    { OA_MIN_OBS: 5 }
    P2_high:   { OA_MIN_OBS: 20 }
    P3_noperson: { drop_categories: [0] }
  families:
    P1_association: { param: "OA_IOU2D / OA_IOU3D", cells: [P1_loose, default, P1_tight], labels: ["0.10/0.15", "0.20/0.30 (default)", "0.40/0.50"] }
    P2_min_obs:     { param: "OA_MIN_OBS",          cells: [P2_low, default, P2_high],     labels: ["5", "10 (default)", "20"] }
    P3_person:      { param: "person landmarks",    cells: [default, P3_noperson],          labels: ["used (default)", "ignored"] }
  control_sequence: mock_control
  control_tolerance_rel: 0.25
execution:
  results_root: results_mock
  cwd: oa_slam_root
  interleave: true
  sleep_between_runs_s: 0
  timeout_s: 300
  min_frame_coverage: 0.90
  retry_failed_once: true
evaluation:
  evo: auto
  ate_align: true
  align_scale: false
  drop_identity_poses: true
  rpe_delta: 1
  max_time_diff_s: 0.02
  jump_threshold_m: 0.5
  log_patterns:
    effective:      "^EFFECTIVE\\\\s+(\\\\w+)\\\\s*=\\\\s*(\\\\S+)"
    landmark_new:   "^LANDMARK_NEW\\\\b"
    assoc_matched:  "^ASSOC\\\\s+\\\\S+\\\\s+matched\\\\b"
    assoc_new:      "^ASSOC\\\\s+\\\\S+\\\\s+new\\\\b"
    lost:           "^LOST\\\\b"
    reloc:          "^RELOC\\\\s+\\\\S+\\\\s+(\\\\d)\\\\s+(\\\\S+)"
    frame_ms:       "^FRAME\\\\s+\\\\S+\\\\s+(\\\\S+)"
    map_objects:    "^Nb Map Objects\\\\s*:\\\\s*(\\\\d+)"
    mean_track_s:   "^mean tracking time:\\\\s*(\\\\S+)"
    median_track_s: "^median tracking time:\\\\s*(\\\\S+)"
"""
    (here / "oa3_config_mock.yaml").write_text(cfg)
    root = here / "mock_root"
    (root / "bin").mkdir(parents=True, exist_ok=True); (root / "Vocabulary").mkdir(exist_ok=True)
    (root / "bin" / "oa-slam").write_text("#!/bin/sh\necho 'mock placeholder: use --mock'\nexit 1\n")
    (root / "Vocabulary" / "ORBvoc.txt").write_text("mock vocabulary\n")
    print("mock dataset in %s (%d frames per sequence); config: %s" % (out, a.frames, here / "oa3_config_mock.yaml"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
